// Generates src/contracts.ts from contracts/schema/*.json. Never hand-edit the output.
// All schemas are merged into one root so shared $defs are emitted once and names never collide.
import { compile } from "json-schema-to-typescript";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../../contracts/schema/", import.meta.url).pathname;
const defs = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const { $defs = {}, ...top } = JSON.parse(readFileSync(join(dir, f), "utf8"));
  Object.assign(defs, $defs, { [top.title]: top });
}
// Property-level titles would become noisy type aliases (Status, Status1, ...); keep only def titles.
const strip = (s, isDef) => {
  if (Array.isArray(s)) return s.map((x) => strip(x, false));
  if (!s || typeof s !== "object") return s;
  const out = {};
  for (const [k, v] of Object.entries(s)) {
    if (k === "title" && !isDef) continue;
    out[k] = k === "properties" ? Object.fromEntries(Object.entries(v).map(([pk, pv]) => [pk, strip(pv, false)])) : strip(v, false);
  }
  return out;
};
const $defs = Object.fromEntries(Object.entries(defs).map(([k, v]) => [k, strip(v, true)]));
const root = {
  title: "Contracts", type: "object", additionalProperties: false, $defs,
  properties: Object.fromEntries(Object.keys($defs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
};
let ts = await compile(root, "Contracts", {
  bannerComment: "/* Generated by scripts/gen-types.mjs from contracts/schema. Do not edit. */",
  additionalProperties: false, unreachableDefinitions: true,
});
writeFileSync(new URL("../src/contracts.ts", import.meta.url), ts);
console.log("wrote src/contracts.ts:", [...ts.matchAll(/^export (?:interface|type) (\w+)/gm)].map((m) => m[1]).join(", "));
